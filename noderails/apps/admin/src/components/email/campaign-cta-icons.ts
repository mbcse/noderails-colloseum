export function findCampaignLucideIcon(name: string): LucideIcon | undefined {
  return CAMPAIGN_LUCIDE_ICONS.find((item) => item.name === name)?.Icon;
}

export function snapshotLucideIcon(Icon: LucideIcon): string {
  const host = document.createElement('div');
  const root = createRoot(host);
  flushSync(() => {
    root.render(createElement(Icon, { width: 16, height: 16, strokeWidth: 2 }));
  });
  const html = host.innerHTML;
  root.unmount();
  return sanitizeCampaignCtaSvg(html);
}
